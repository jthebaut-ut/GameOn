def is_ui_key(key: str) -> bool:
    if not key or len(key.strip()) < 2:
        return False
    if re.fullmatch(r"[\s\W\d]+", key):
        return False
    if key in {"@alexmorgan", "@fangeosports", "you@email.com"}:
        return False
    return True


def merge_key(strings: dict, key: str, values: dict[str, str]) -> None:
    if "en" not in values and key:
        values = {**values, "en": key}
    entry = strings.setdefault(key, {})
    locs = entry.setdefault("localizations", {})
    for lang in SUPPORTED:
        if lang not in values:
            continue
        locs[lang] = unit(values[lang])
    entry["extractionState"] = "manual"


def catalog_entry_count(strings: dict) -> int:
    return len(strings)


def supported_locale_coverage(strings: dict) -> dict[str, int]:
    coverage = {lang: 0 for lang in SUPPORTED}
    for entry in strings.values():
        locs = entry.get("localizations") or {}
        for lang in SUPPORTED:
            try:
                val = locs[lang]["stringUnit"]["value"]
            except Exception:
                continue
            if isinstance(val, str) and val.strip():
                coverage[lang] += 1
    return coverage


